"""Builds supabase/auto-entries.sql from data/auto-entries.json.

Looks up coordinates with OpenStreetMap Nominatim (1 request per second) and caches them in the JSON.
Usage: python3 tools/build_auto_sql.py
Then run supabase/auto-entries.sql in the Supabase SQL editor (safe to run again).
It also writes supabase/auto-entries-update.sql: refreshes contacts (Instagram, e-mail, WhatsApp) and disciplines
of auto entries that already exist. Claimed entries are not touched (they are no longer is_auto).
Fields only kept in the JSON for later: brands, efoil_brands, assist_brands, hours_raw.
"""
import json, os, time, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "auto-entries.json")
OUT = os.path.join(ROOT, "supabase", "auto-entries.sql")
OUT_UPD = os.path.join(ROOT, "supabase", "auto-entries-update.sql")

entries = json.load(open(SRC, encoding="utf-8"))
for e in entries:
    if "lat" in e:
        continue
    url = "https://nominatim.openstreetmap.org/search?format=jsonv2&limit=1&q=" + urllib.parse.quote(e["q"])
    req = urllib.request.Request(url, headers={"User-Agent": "wearefoilers-map-builder/1.0"})
    res = json.load(urllib.request.urlopen(req, timeout=20))
    if not res:
        json.dump(entries, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        raise SystemExit("No result for " + e["q"])
    e["lat"], e["lng"] = round(float(res[0]["lat"]), 5), round(float(res[0]["lon"]), 5)
    print(f'{e["name"]}: {e["lat"]}, {e["lng"]}  ({res[0]["display_name"][:70]})')
    time.sleep(1.1)
json.dump(entries, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

def q(s):
    return "'" + str(s).replace("'", "''") + "'"

def qn(s):
    return q(s) if s else "null"

rows, upd = [], []
for e in entries:
    disc = [{"id": d.split(":")[0], "level": int(d.split(":")[1])} for d in e["disc"].split(",")]
    kind = "school" if e["type"] == "school" else "shop"
    about = f"Foil {'lessons and rental' if kind == 'school' else 'gear and advice'} in {e['label'].split(',')[0]}. Details and booking on their website."
    contact = dict(ig=qn(e.get("instagram")), wa=qn(e.get("whatsapp")), em=qn(e.get("email")))
    rows.append("(md5({n})::uuid, {t}, {n}, {lbl}, {lat}, {lng}, {disc}::jsonb, {open}, {about}, {web}, {ig}, {wa}, {em}, true, {web}, 'approved')".format(
        n=q(e["name"]), t=q(e["type"]), lbl=q(e["label"]), lat=e["lat"], lng=e["lng"], disc=q(json.dumps(disc)),
        open="'{}'", about=q(about), web=q(e["web"]), **contact))
    upd.append("(md5({n})::uuid, {disc}::jsonb, {ig}, {wa}, {em})".format(n=q(e["name"]), disc=q(json.dumps(disc)), **contact))

sql = """-- Automatic entries: real foil schools and shops from public info (generated by tools/build_auto_sql.py).
-- Each card says it was added automatically; the business can claim it from the card.
-- Safe to run again: existing entries are kept, deleted ones come back (remove them from the JSON instead).
insert into public.profiles (id, type, name, home_label, home_lat, home_lng, disciplines, open_for, about, website, instagram, whatsapp, email, is_auto, source_url, status)
values
""" + ",\n".join(rows) + "\non conflict (id) do nothing;\n"
open(OUT, "w", encoding="utf-8").write(sql)
print("wrote", OUT, len(rows), "entries")

upd_sql = """-- Refresh contacts and disciplines of existing auto entries (generated by tools/build_auto_sql.py).
-- Only rows that are still auto entries are changed; claimed entries are left alone. Safe to run again.
update public.profiles p
set disciplines = v.disciplines, instagram = v.instagram, whatsapp = v.whatsapp, email = v.email
from (values
""" + ",\n".join(upd) + """
) as v(id, disciplines, instagram, whatsapp, email)
where p.id = v.id and p.is_auto;
"""
open(OUT_UPD, "w", encoding="utf-8").write(upd_sql)
print("wrote", OUT_UPD, len(upd), "entries")
